    #[test]
    fn crc32c_empty_and_incremental() {
        assert_eq!(crc32c(&[], 0), 0);
        assert_ne!(crc32c(b"SOMEDATA", 0), 0);
        // Incremental computation equals one-shot
        let whole = crc32c(b"123456789", 0);
        let part = crc32c(b"6789", crc32c(b"12345", 0));
        assert_eq!(whole, part);
        assert_eq!(whole, 0xe3069283);
    }
