//! CRC-32C (Castagnoli), used for miniSEED 3 record integrity.
//!
//! Slicing-by-16: sixteen lookup tables let each step fold 16 input bytes into the CRC
//! with independent table lookups, several times faster than one table and one byte per
//! step, in safe and portable Rust.

/// Reflected CRC-32C polynomial.
const POLY: u32 = 0x82F6_3B78;

/// `TABLES[0]` is the byte-at-a-time table; `TABLES[k][b]` is the CRC contribution of
/// byte `b` followed by `k` zero bytes.
const fn make_tables() -> [[u32; 256]; 16] {
    let mut tables = [[0u32; 256]; 16];
    let mut i = 0;
    while i < 256 {
        let mut crc = i as u32;
        let mut j = 0;
        while j < 8 {
            crc = if crc & 1 != 0 { (crc >> 1) ^ POLY } else { crc >> 1 };
            j += 1;
        }
        tables[0][i] = crc;
        i += 1;
    }
    let mut k = 1;
    while k < 16 {
        let mut i = 0;
        while i < 256 {
            let prev = tables[k - 1][i];
            tables[k][i] = (prev >> 8) ^ tables[0][(prev & 0xff) as usize];
            i += 1;
        }
        k += 1;
    }
    tables
}

static TABLES: [[u32; 256]; 16] = make_tables();

/// Compute the CRC-32C of `input`, continuing from `previous` (use 0 to start).
#[must_use]
pub(crate) fn crc32c(input: &[u8], previous: u32) -> u32 {
    let t = &TABLES;
    let mut crc = !previous;
    let mut blocks = input.chunks_exact(16);
    for b in &mut blocks {
        // The CRC is folded into the first four bytes; byte `j` of the block is followed
        // by `15 - j` bytes, so it is looked up in table `15 - j`
        let a = crc ^ u32::from_le_bytes([b[0], b[1], b[2], b[3]]);
        crc = t[15][(a & 0xff) as usize]
            ^ t[14][((a >> 8) & 0xff) as usize]
            ^ t[13][((a >> 16) & 0xff) as usize]
            ^ t[12][(a >> 24) as usize]
            ^ t[11][b[4] as usize]
            ^ t[10][b[5] as usize]
            ^ t[9][b[6] as usize]
            ^ t[8][b[7] as usize]
            ^ t[7][b[8] as usize]
            ^ t[6][b[9] as usize]
            ^ t[5][b[10] as usize]
            ^ t[4][b[11] as usize]
            ^ t[3][b[12] as usize]
            ^ t[2][b[13] as usize]
            ^ t[1][b[14] as usize]
            ^ t[0][b[15] as usize];
    }
    for &b in blocks.remainder() {
        crc = (crc >> 8) ^ t[0][((crc as u8) ^ b) as usize];
    }
    !crc
}

