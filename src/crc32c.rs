    /// The plain byte-at-a-time CRC, as reference.
    fn crc32c_bytewise(input: &[u8], previous: u32) -> u32 {
        let mut crc = !previous;
        for &b in input {
            crc = (crc >> 8) ^ TABLES[0][((crc as u8) ^ b) as usize];
        }
        !crc
    }

    /// Every length, alignment and split point matches the byte-at-a-time CRC.
    #[test]
    fn crc32c_matches_bytewise() {
        let data: Vec<u8> =
            (0u32..300).map(|i| (i.wrapping_mul(2_654_435_761) >> 13) as u8).collect();
        for start in 0..17 {
            for end in start..data.len() {
                let s = &data[start..end];
                assert_eq!(crc32c(s, 0), crc32c_bytewise(s, 0), "{start}..{end}");
            }
        }
        for split in 0..data.len() {
            let (a, b) = data.split_at(split);
            assert_eq!(crc32c(b, crc32c(a, 0)), crc32c_bytewise(&data, 0), "split {split}");
        }
    }

